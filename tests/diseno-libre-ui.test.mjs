import test from 'node:test'
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdir, readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { servidorPrueba } from './portal-helper.mjs'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')

test('Diseño libre: arrastre real, cancelación, giros, alineación, copias, historial, PDF y reapertura', { timeout: 180000 }, async (t) => {
  const { base, request, admin, sesion, carpeta } = await servidorPrueba(t)
  const browser = await chromium.launch({ headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'],
    ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) })
  t.after(() => browser.close())
  const context = await browser.newContext({ viewport: { width: 1600, height: 1150 }, serviceWorkers: 'block', hasTouch: true })
  await context.addInitScript((s) => {
    sessionStorage.setItem('nomina_token', s.token); sessionStorage.setItem('nomina_user', 'admin'); sessionStorage.setItem('nomina_rol', 'admin')
  }, sesion)
  const page = await context.newPage(), errores = []
  page.on('pageerror', (e) => errores.push(e.message))
  const output = process.env.UI_SCREENSHOT_DIR || carpeta
  await mkdir(output, { recursive: true })
  t.after(async () => { if (!page.isClosed()) await page.screenshot({ path: join(output, 'libre-final.png'), fullPage: true }).catch(() => {}) })
  await page.goto(`${base}/cortes-planos`)
  await page.getByLabel('Nombre del proyecto', { exact: true }).fill('Armario de diseño libre')
  await page.getByRole('tab', { name: 'Diseño libre', exact: true }).click()
  const libre = page.getByRole('region', { name: 'Editor de diseño libre' })
  const canvas = page.getByLabel('Diseño libre 3D interactivo', { exact: true })
  await page.locator('canvas[data-estado="listo"]').waitFor()
  const campo = (label) => libre.getByLabel(`Tablero · ${label}`, { exact: true })
  await campo('Nombre').fill('Lateral izquierdo')
  await campo('Ancho (cm)').fill('50')
  await campo('Alto / largo (cm)').fill('180')
  await campo('Orientación').selectOption('lateral')
  await libre.getByRole('button', { name: 'Crear tablero', exact: true }).click()
  assert.equal(await canvas.getAttribute('data-piezas-visibles'), '1')
  await libre.getByRole('button', { name: 'Frente', exact: true }).click()
  await libre.getByRole('button', { name: 'Mover tablero', exact: true }).click()
  await libre.getByLabel('Eje de arrastre', { exact: true }).selectOption('x')
  await libre.getByLabel('Ajustar a caras', { exact: true }).uncheck()
  await canvas.scrollIntoViewIfNeeded()
  let box = await canvas.boundingBox()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 100, box.y + box.height / 2 + 20, { steps: 8 })
  await page.mouse.up()
  const movido = Number(await campo('X (mm)').inputValue())
  assert.ok(movido > 0, 'El arrastre movió el tablero en el espacio 3D')
  assert.equal(movido % 10, 0)
  assert.equal(await campo('Y (mm)').inputValue(), '0')
  assert.equal(await campo('Z (mm)').inputValue(), '0')
  await page.getByRole('button', { name: 'Deshacer', exact: true }).click()
  assert.equal(await campo('X (mm)').inputValue(), '0', 'Un solo Deshacer revierte el arrastre completo')
  await page.getByRole('button', { name: 'Rehacer', exact: true }).click()
  assert.equal(Number(await campo('X (mm)').inputValue()), movido)
  await page.getByRole('button', { name: 'Deshacer', exact: true }).click()
  await canvas.scrollIntoViewIfNeeded(); box = await canvas.boundingBox()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 80, box.y + box.height / 2, { steps: 5 })
  await page.keyboard.press('Escape'); await page.mouse.up()
  assert.equal(await campo('X (mm)').inputValue(), '0', 'Escape cancela el arrastre sin guardar la posición temporal')
  await libre.getByText('Girar y copiar', { exact: true }).click()
  await libre.getByLabel('Separación de copia (mm)', { exact: true }).fill('982')
  await libre.getByRole('button', { name: 'Duplicar tablero', exact: true }).click()
  assert.equal(await canvas.getAttribute('data-piezas-visibles'), '2')
  assert.equal(await campo('X (mm)').inputValue(), '982')
  await libre.getByRole('button', { name: 'Girar Y 90°', exact: true }).click()
  assert.equal(await campo('Orientación').inputValue(), 'frente')
  await page.getByRole('button', { name: 'Deshacer', exact: true }).click()
  assert.equal(await campo('Orientación').inputValue(), 'lateral')
  await libre.getByText('Alinear o unir caras', { exact: true }).click()
  await libre.getByLabel('Tablero de referencia', { exact: true }).selectOption('P001-1')
  await libre.getByRole('button', { name: 'Aplicar alineación', exact: true }).click()
  assert.equal(await campo('X (mm)').inputValue(), '18')
  await page.getByRole('button', { name: 'Deshacer', exact: true }).click()
  assert.equal(await campo('X (mm)').inputValue(), '982')
  await libre.getByRole('button', { name: 'Nuevo tablero', exact: true }).click()
  await campo('Nombre').fill('Repisa inferior')
  await campo('Ancho (cm)').fill('96.4')
  await campo('Alto / largo (cm)').fill('50')
  await campo('Orientación').selectOption('horizontal')
  await campo('X (mm)').fill('18')
  await libre.getByRole('button', { name: 'Crear tablero', exact: true }).click()
  await libre.getByText('Girar y copiar', { exact: true }).click()
  await libre.getByLabel('Eje de copia', { exact: true }).selectOption('y')
  await libre.getByLabel('Separación de copia (mm)', { exact: true }).fill('1782')
  await libre.getByRole('button', { name: 'Duplicar tablero', exact: true }).click()
  await libre.getByLabel('Separación de copia (mm)', { exact: true }).fill('-882')
  await libre.getByRole('button', { name: 'Duplicar tablero', exact: true }).click()
  assert.equal(await canvas.getAttribute('data-piezas-visibles'), '5')
  await libre.getByRole('button', { name: 'Eliminar esta unidad', exact: true }).click()
  assert.equal(await canvas.getAttribute('data-piezas-visibles'), '4')
  await page.getByRole('button', { name: 'Deshacer', exact: true }).click()
  assert.equal(await canvas.getAttribute('data-piezas-visibles'), '5')
  await libre.getByRole('button', { name: 'Ajustar vista libre', exact: true }).click()
  await libre.getByText('Apariencia del área 3D', { exact: true }).click()
  await libre.getByLabel('Acabado diseño libre', { exact: true }).selectOption('roble')
  await libre.screenshot({ path: join(output, 'libre-armario-escritorio.png') })
  await page.getByRole('button', { name: 'Guardar version', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.corte-subtitle')?.textContent.endsWith('Guardado'))
  const lista = (await request('/planos-corte', 'GET', undefined, admin)).data
  const guardado = (await request(`/planos-corte/${lista[0].id}`, 'GET', undefined, admin)).data
  assert.equal(guardado.proyecto.disenoLibre, true)
  assert.equal(guardado.proyecto.montajeManual.length, 5)
  assert.equal(guardado.proyecto.piezas.find((p) => p.codigo === 'P003').ancho, 964)
  const descarga = page.waitForEvent('download')
  await page.getByRole('button', { name: 'PDF de taller', exact: true }).click()
  const pdf = join(output, 'libre-armario.pdf')
  await (await descarga).saveAs(pdf)
  assert.ok((await readFile(pdf)).toString('latin1').includes('VISTAS TECNICAS DEL MUEBLE'))
  await libre.getByRole('button', { name: 'Ver despiece y corte', exact: true }).click()
  assert.equal(await page.locator('.corte-pieces tbody tr').count(), 5)
  await page.getByRole('button', { name: 'Nuevo proyecto', exact: true }).click()
  await page.getByRole('button', { name: 'Proyectos', exact: true }).click()
  await page.getByRole('button', { name: 'Abrir', exact: true }).first().click()
  await page.getByRole('region', { name: 'Editor de diseño libre' }).waitFor()
  assert.equal(await canvas.getAttribute('data-piezas-visibles'), '5')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 0)
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Sin desbordamiento en móvil')
  await libre.getByRole('button', { name: 'Ampliar diseño libre', exact: true }).click()
  const salir = libre.getByRole('button', { name: 'Reducir diseño libre', exact: true })
  assert.ok(await salir.evaluate((el) => {
    const r = el.getBoundingClientRect()
    return r.top >= 0 && r.bottom <= innerHeight && r.left >= 0 && r.right <= innerWidth
  }))
  await libre.getByLabel('Tablero de diseño libre', { exact: true }).selectOption('P001-1')
  await libre.getByRole('button', { name: 'Mover tablero', exact: true }).click()
  await libre.getByLabel('Eje de arrastre', { exact: true }).selectOption('x')
  await libre.getByLabel('Ajustar a caras', { exact: true }).uncheck()
  await canvas.scrollIntoViewIfNeeded()
  const toque = await canvas.evaluate((c) => {
    const gl = c.getContext('webgl'), pixels = new Uint8Array(c.width * 4), y = Math.floor(c.height / 2)
    gl.readPixels(0, y, c.width, 1, gl.RGBA, gl.UNSIGNED_BYTE, pixels)
    const xs = []
    for (let x = 0; x < c.width; x++) if (pixels[x * 4 + 1] > 70 && pixels[x * 4 + 1] > pixels[x * 4] * 1.4 && pixels[x * 4 + 2] > pixels[x * 4] * 1.4) xs.push(x)
    const r = c.getBoundingClientRect()
    return xs.length ? { x: r.x + xs[Math.floor(xs.length / 2)] / c.width * r.width, y: r.y + r.height / 2 } : null
  })
  assert.ok(toque, 'Se localiza visualmente el tablero seleccionado en móvil')
  const tactil = await context.newCDPSession(page)
  await tactil.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: toque.x, y: toque.y }] })
  await tactil.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: toque.x + 40, y: toque.y }] })
  await tactil.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  assert.ok(Number(await campo('X (mm)').inputValue()) > 0, 'El gesto táctil mueve el tablero')
  await libre.getByRole('button', { name: 'Deshacer diseño libre', exact: true }).click()
  assert.equal(await campo('X (mm)').inputValue(), '0')
  await libre.screenshot({ path: join(output, 'libre-movil-completo.png') })
  await salir.click()
  await libre.screenshot({ path: join(output, 'libre-movil.png') })
  assert.deepEqual(errores, [])
})
